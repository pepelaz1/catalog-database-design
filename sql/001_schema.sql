BEGIN;

CREATE SCHEMA catalog;

CREATE TABLE catalog.category (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE CHECK (length(btrim(name)) > 0)
);

CREATE TABLE catalog.product (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku text NOT NULL UNIQUE CHECK (length(btrim(sku)) > 0),
    name text NOT NULL CHECK (length(btrim(name)) > 0),
    brand text,
    category_id bigint NOT NULL REFERENCES catalog.category(id) ON DELETE RESTRICT
);

CREATE TABLE catalog.supplier (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE CHECK (length(btrim(name)) > 0),
    active boolean NOT NULL DEFAULT true
);

CREATE TABLE catalog.supplier_offer (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id bigint NOT NULL REFERENCES catalog.supplier(id) ON DELETE RESTRICT,
    product_id bigint NOT NULL REFERENCES catalog.product(id) ON DELETE RESTRICT,
    supplier_sku text NOT NULL CHECK (length(btrim(supplier_sku)) > 0),
    currency text NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
    source_url text,
    UNIQUE (supplier_id, supplier_sku),
    UNIQUE (id, supplier_id)
);

CREATE TABLE catalog.import_batch (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id bigint NOT NULL REFERENCES catalog.supplier(id) ON DELETE RESTRICT,
    source_file text NOT NULL CHECK (length(btrim(source_file)) > 0),
    started_at timestamptz NOT NULL DEFAULT now(),
    status text NOT NULL CHECK (status IN ('started', 'completed', 'failed')),
    UNIQUE (id, supplier_id)
);

CREATE TABLE catalog.price_observation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offer_id bigint NOT NULL,
    supplier_id bigint NOT NULL,
    batch_id bigint NOT NULL,
    observed_at timestamptz NOT NULL,
    price numeric(14,2) NOT NULL CHECK (price >= 0),
    available boolean NOT NULL,
    FOREIGN KEY (offer_id, supplier_id)
        REFERENCES catalog.supplier_offer(id, supplier_id) ON DELETE RESTRICT,
    FOREIGN KEY (batch_id, supplier_id)
        REFERENCES catalog.import_batch(id, supplier_id) ON DELETE RESTRICT,
    UNIQUE (batch_id, offer_id)
);

CREATE INDEX product_category_idx ON catalog.product(category_id);
CREATE INDEX supplier_offer_product_idx ON catalog.supplier_offer(product_id);
CREATE INDEX import_batch_supplier_time_idx
    ON catalog.import_batch(supplier_id, started_at DESC);
CREATE INDEX import_batch_status_idx ON catalog.import_batch(status)
    WHERE status <> 'completed';
CREATE INDEX price_observation_offer_time_idx
    ON catalog.price_observation(offer_id, observed_at DESC, id DESC);

CREATE VIEW catalog.latest_offer_state AS
SELECT DISTINCT ON (o.id)
    o.id AS offer_id,
    o.supplier_id,
    o.product_id,
    o.supplier_sku,
    o.currency,
    p.price,
    p.available,
    p.observed_at,
    p.batch_id
FROM catalog.supplier_offer AS o
JOIN catalog.price_observation AS p ON p.offer_id = o.id
ORDER BY o.id, p.observed_at DESC, p.id DESC;

COMMIT;
